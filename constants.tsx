// Função para obter o domingo da semana de uma data
const getSundayOfWeek = (date: Date): Date => {
  const day = date.getDay();
  const diff = date.getDate() - day; // Ajusta para o domingo (dia 0)
  return new Date(date.getFullYear(), date.getMonth(), diff);
};

// Função para formatar data no formato DD/MM
const formatDate = (date: Date): string => {
  const day = String(date.getDate()).padStart(2, '0');
  const month = String(date.getMonth() + 1).padStart(2, '0');
  return `${day}/${month}`;
};

// Função para obter o nome do mês em português
const getMonthName = (monthIndex: number): string => {
  const months = [
    'JANEIRO', 'FEVEREIRO', 'MARÇO', 'ABRIL', 'MAIO', 'JUNHO',
    'JULHO', 'AGOSTO', 'SETEMBRO', 'OUTUBRO', 'NOVEMBRO', 'DEZEMBRO'
  ];
  return months[monthIndex];
};

// Função para gerar semanas dinamicamente
const generateWeeks = (numberOfWeeks: number = 52) => {
  // DATA FIXA DE INÍCIO: 05 de Janeiro de 2026 (Segunda-feira)
  // Ciclo Segunda a Domingo
  const anchorDate = new Date(2026, 0, 5);

  const weeks: any[] = [];

  for (let i = 0; i < numberOfWeeks; i++) {
    const weekStart = new Date(anchorDate);
    weekStart.setDate(anchorDate.getDate() + (i * 7));

    const weekEnd = new Date(weekStart);
    weekEnd.setDate(weekStart.getDate() + 6);

    const monthName = getMonthName(weekStart.getMonth());
    const year = weekStart.getFullYear();
    const range = `${formatDate(weekStart)} - ${formatDate(weekEnd)}`;

    weeks.push({
      id: `w${i + 1}`,
      n: i + 1,
      range,
      label: `Semana ${i + 1}`,
      month: `${monthName} ${year}`,
      monthIndex: weekStart.getMonth(),
      year,
      startDate: weekStart,
      endDate: weekEnd
    });
  }

  return weeks;
};

// Função para agrupar semanas por mês
const groupWeeksByMonth = (weeks: any[]) => {
  const grouped: { [key: string]: any } = {};

  weeks.forEach(week => {
    const key = `${week.month}`;
    if (!grouped[key]) {
      grouped[key] = {
        name: key,
        weeks: []
      };
    }

    // Calcular o número da semana dentro do mês
    const weeksInMonth = grouped[key].weeks.length + 1;
    grouped[key].weeks.push({
      ...week,
      n: weeksInMonth,
      label: `Semana ${weeksInMonth} de ${getMonthName(week.monthIndex)}/${week.year}`
    });
  });

  return Object.values(grouped);
};

// Gerar semanas para o ano todo (fixo a partir de 11/01/26)
const allWeeks = generateWeeks(52);
export const MONTHS = groupWeeksByMonth(allWeeks);

// Semana atual como padrão
export const WEEKS: any[] = allWeeks;

// Helper para encontrar a semana atual baseada na data de hoje
const today = new Date();
export const CURRENT_WEEK = allWeeks.find(w => today >= w.startDate && today <= w.endDate) || allWeeks[0];
